# shellcheck shell=bash
# GRUB2 themes (git submodules) copied to <stick>/ventoy/theme/<name>/.

THEMES_DIR="$REPO_DIR/themes"

# name -> source directory inside the submodules. Vimix is generated below.
declare -A THEME_SRC=(
    # Catppuccin ships a Ventoy-specific variant next to its GRUB theme.
    [catppuccin-mocha]="$THEMES_DIR/catppuccin-grub/ventoy/src/mocha/catppuccin-mocha"
    [tokyo-night]="$THEMES_DIR/tokyo-night-grub/tokyo-night"
)
THEME_ORDER=(catppuccin-mocha tokyo-night vimix)

themes_check_submodules() {
    local sub
    for sub in catppuccin-grub tokyo-night-grub grub2-themes; do
        [[ -n $(ls -A "$THEMES_DIR/$sub" 2>/dev/null) ]] \
            || die "themes/$sub is empty — run: git submodule update --init --recursive"
    done
}

# Vimix has to be generated by grub2-themes' installer (it assembles the
# theme from shared assets for the chosen icon set and resolution).
themes_generate_vimix() {
    local out=$1
    (cd "$THEMES_DIR/grub2-themes" && ./install.sh -t vimix -i color -s 1080p -g "$out") >/dev/null \
        || die "grub2-themes failed to generate vimix"
    [[ -f $out/vimix/theme.txt ]] || die "vimix was not generated into $out/vimix"
}

themes_install() {
    local mnt=$1 tmp name src dest
    themes_check_submodules
    tmp=$(make_tmp)
    themes_generate_vimix "$tmp"
    THEME_SRC[vimix]="$tmp/vimix"

    for name in "${THEME_ORDER[@]}"; do
        src=${THEME_SRC[$name]}
        [[ -f $src/theme.txt ]] || die "theme '$name' has no theme.txt in $src"
        dest="$mnt/ventoy/theme/$name"
        log "theme $name -> ${dest#"$mnt"}"
        run rm -rf "$dest"
        run mkdir -p "$dest"
        run cp -r "$src/." "$dest/"
        if ! is_dry_run; then
            [[ -f $dest/theme.txt ]] || die "copy failed: $dest/theme.txt missing"
        fi
    done
    ok "themes installed: ${THEME_ORDER[*]}"
}

# themes_on_stick MNT: theme.txt paths (as Ventoy sees them) found on the
# stick — the built-in three first, then any themes the user added.
themes_on_stick() {
    local mnt=$1 name dir
    for name in "${THEME_ORDER[@]}"; do
        [[ -f $mnt/ventoy/theme/$name/theme.txt ]] && echo "/ventoy/theme/$name/theme.txt"
    done
    for dir in "$mnt"/ventoy/theme/*/; do
        name=$(basename "$dir")
        [[ -f $dir/theme.txt ]] || continue
        [[ " ${THEME_ORDER[*]} " == *" $name "* ]] && continue
        echo "/ventoy/theme/$name/theme.txt"
    done
}
