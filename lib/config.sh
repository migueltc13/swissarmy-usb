# shellcheck shell=bash
# Generate <stick>/ventoy/ventoy.json and <stick>/Files/isos.md from the
# manifest plus the per-ISO state recorded by `setup.sh isos`.

CONFIG_TMPL="$REPO_DIR/config/ventoy.tmpl.json"

# iso_tip ID STATEFILE: "version · language · description"
iso_tip() {
    local id=$1 state=$2 version part out=''
    version=$(kv_get "$state" VERSION)
    [[ $version == manual ]] && version=''
    for part in "$version" "$(m "$id" lang)" "$(m "$id" tip)"; do
        [[ -n $part ]] && out+="${out:+ · }$part"
    done
    printf '%s' "$out"
}

# config_generated MNT: the generated part of ventoy.json (theme files,
# aliases, tips, persistence) as JSON on stdout. Ventoy loads the .pf2 fonts
# next to the chosen theme.txt by itself, so no "fonts" list is needed.
config_generated() {
    local mnt=$1 id folder state dat name
    local -a themes=() items=()

    mapfile -t themes < <(themes_on_stick "$mnt")
    ((${#themes[@]})) || warn "no themes on the stick yet (run: $PROG themes)"

    for folder in "${FOLDER_IDS[@]}"; do
        items+=("$(jq -nc --arg d "/$folder" --arg a "$(m "folder:$folder" alias)" --arg t "$(m "folder:$folder" tip)" \
            '{alias: {dir: $d, alias: $a}, tip: {dir: $d, tip: $t}}')")
    done
    for id in "${ISO_IDS[@]}"; do
        [[ -f $mnt$(iso_path "$id") ]] || continue
        state="$(state_dir "$mnt")/$id.env"
        items+=("$(jq -nc --arg i "$(iso_path "$id")" --arg a "$(m "$id" alias)" --arg t "$(iso_tip "$id" "$state")" \
            '{alias: {image: $i, alias: $a}, tip: {image: $i, tip: $t}}')")
    done
    for dat in "$mnt"/ventoy/persistence/*.dat; do
        [[ -f $dat ]] || continue
        name=$(basename "$dat" .dat)
        id=$(persistence_entry "$name") || { warn "ignoring ventoy/persistence/$name.dat (no matching ISO)"; continue; }
        items+=("$(jq -nc --arg i "$(iso_path "$id")" --arg b "/ventoy/persistence/$name.dat" \
            '{persistence: {image: $i, backend: $b}}')")
    done

    printf '%s\n' "${items[@]}" | jq -s \
        --argjson themes "$(printf '%s\n' "${themes[@]}" | jq -R . | jq -sc 'map(select(. != ""))')" '
        {
          menu_alias: [.[] | .alias | select(. != null)],
          menu_tip: {tips: [.[] | .tip | select(. != null)]}
        }
        + (if ($themes | length) > 0
           then {theme: {file: $themes}}
           else {} end)
        + (if any(.[]; .persistence) then {persistence: [.[] | .persistence | select(. != null)]} else {} end)'
}

# config_validate FILE: valid JSON with the blocks Ventoy needs.
config_validate() {
    jq -e '
        (.theme == null
          or ((.theme.file | type == "array" and length > 0)
              and (.theme.default_file | type == "number")))
        and (.menu_alias | type == "array")
        and (.menu_tip.tips | type == "array")
    ' "$1" >/dev/null
}

# md_table: read tab-separated rows (the first one is the header) and print
# a Markdown table with aligned columns, the way prettier formats it. Every
# cell must be non-empty (use "-"), since read collapses empty tab fields.
md_table() {
    local LC_ALL=C.UTF-8 # count characters, not bytes (names may be UTF-8)
    local -a rows=() widths=() cells
    local row i cell out

    while IFS= read -r row; do
        rows+=("$row")
        IFS=$'\t' read -r -a cells <<<"$row"
        for i in "${!cells[@]}"; do
            ((${#cells[i]} > ${widths[i]:-3})) && widths[i]=${#cells[i]}
        done
    done

    for i in "${!rows[@]}"; do
        IFS=$'\t' read -r -a cells <<<"${rows[i]}"
        out='|'
        for cell in "${!cells[@]}"; do
            out+=" ${cells[cell]}$(printf '%*s' $((widths[cell] - ${#cells[cell]})) '') |"
        done
        echo "$out"
        if ((i == 0)); then
            out='|'
            for cell in "${!widths[@]}"; do
                out+=" $(printf '%*s' "${widths[cell]}" '' | tr ' ' '-') |"
            done
            echo "$out"
        fi
    done
}

# shellcheck disable=SC2016  # the backticks are Markdown code spans
config_isos_md() {
    local mnt=$1 folder id state version date url sha
    printf '# ISOs on this stick\n\n'
    printf 'Generated by swissarmy-usb on %s.\n' "$(date -u '+%Y-%m-%d %H:%M UTC')"
    printf 'Check a file with `sha256sum <file>` and compare it with the SHA256 column.\n'

    for folder in "${FOLDER_IDS[@]}"; do
        printf '\n## %s (`%s/`)\n\n' "$(m "folder:$folder" alias)" "$folder"
        {
            printf 'Name\tFile\tVersion\tLanguage\tDownloaded\tSource\tSHA256\n'
            for id in "${ISO_IDS[@]}"; do
                [[ $(m "$id" folder) == "$folder" ]] || continue
                state="$(state_dir "$mnt")/$id.env"
                version=$(kv_get "$state" VERSION) date=$(kv_get "$state" DATE)
                url=$(kv_get "$state" URL) sha=$(kv_get "$state" SHA256)
                [[ -n $url ]] || url=$(m "$id" url)
                if [[ ! -f $mnt$(iso_path "$id") ]]; then
                    version=missing date='' sha=''
                fi
                [[ $version == manual ]] && version=''
                is_manual "$id" && version="${version:+$version }(manual)"
                printf '%s\t`%s`\t%s\t%s\t%s\t%s\t%s\n' \
                    "$(m "$id" alias)" "$(m "$id" file)" "${version:--}" "$(m "$id" lang)" \
                    "${date:--}" "${url:--}" "${sha:+\`$sha\`}"
            done
        } | sed -e 's/\t\t/\t-\t/g' -e 's/\t\t/\t-\t/g' -e 's/\t$/\t-/' | md_table
    done
}

config_write() {
    local mnt=$1 tmp json
    [[ -f $CONFIG_TMPL ]] || die "missing $CONFIG_TMPL"
    jq empty "$CONFIG_TMPL" || die "config/ventoy.tmpl.json is not valid JSON"
    tmp=$(make_tmp)
    config_generated "$mnt" >"$tmp/generated.json"
    # Template first so it carries user settings; generated lists are merged in.
    # Without any theme on the stick, drop the template's theme settings too.
    jq -s '.[0] * .[1] | if .theme.file == null then del(.theme) else . end' \
        "$CONFIG_TMPL" "$tmp/generated.json" >"$tmp/ventoy.json"
    config_validate "$tmp/ventoy.json" || die "generated ventoy.json failed validation: $tmp/ventoy.json"
    config_isos_md "$mnt" >"$tmp/isos.md"

    if is_dry_run; then
        log "dry-run: would write ventoy/ventoy.json:"
        jq . "$tmp/ventoy.json"
        log "dry-run: would write Files/isos.md:"
        cat "$tmp/isos.md"
        return
    fi
    mkdir -p "$mnt/ventoy" "$mnt/Files"
    json="$mnt/ventoy/ventoy.json"
    [[ -f $json ]] && cp "$json" "$json.bak"
    cp "$tmp/ventoy.json" "$json"
    cp "$tmp/isos.md" "$mnt/Files/isos.md"
    ok "wrote ventoy/ventoy.json ($(jq '.menu_alias | length' "$json") aliases) and Files/isos.md"
}
